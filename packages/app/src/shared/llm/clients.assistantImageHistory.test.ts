import { describe, expect, it, vi } from 'vitest'
import { ClaudeAPICli, OpenAIAPICli } from './clients'
import type { LLMChatParams } from './types'

const userImage =
  'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR4nGMwSjnxHwAEiAJeVQbffQAAAABJRU5ErkJggg=='
const generatedImage =
  'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR4nGP4z8DwHwAFAAH/iZk9HQAAAABJRU5ErkJggg=='
const messages = (): LLMChatParams['messages'] => [
  { role: 'user', content: 'original reference', attachments: [{ type: 'image', url: userImage }] },
  {
    role: 'assistant',
    content: 'generated reference',
    attachments: [
      { type: 'image', url: generatedImage },
      { type: 'file', url: 'https://owned.test/notes.txt', fileName: 'notes.txt' }
    ]
  },
  { role: 'user', content: 'compare those two images' }
]

function setup(provider: 'openai' | 'claude') {
  const fetchImpl = vi
    .fn<typeof fetch>()
    .mockImplementation(
      async () =>
        new Response(
          JSON.stringify(
            provider === 'openai'
              ? { choices: [{ message: { content: 'ok' }, finish_reason: 'stop' }] }
              : { content: [{ type: 'text', text: 'ok' }], stop_reason: 'end_turn' }
          ),
          { headers: { 'content-type': 'application/json' } }
        )
    )
  const client =
    provider === 'openai'
      ? new OpenAIAPICli('owned', 'https://owned.test/v1/chat/completions', 'owned-model', {
          apiMode: 'chat-completions',
          enableHostedTools: false,
          fetchImpl
        })
      : new ClaudeAPICli('owned', 'https://owned.test', 'owned-model', { fetchImpl })
  return { client, fetchImpl }
}

describe('provider projection of selected assistant image history', () => {
  it.each(['openai', 'claude'] as const)(
    '%s includes distinct original and generated bytes without mutating assistant history',
    async (provider) => {
      const { client, fetchImpl } = setup(provider)
      const input = messages()
      const before = structuredClone(input)
      await client.chat({ messages: input, imageHistoryPolicy: 'all' })
      const body = JSON.parse(String(fetchImpl.mock.calls[0][1]?.body))
      const serialized = JSON.stringify(body.messages)
      expect(serialized).toContain(userImage.split(',')[1])
      expect(serialized).toContain(generatedImage.split(',')[1])
      expect(body.messages.map((m: { role: string }) => m.role)).toEqual([
        'user',
        'assistant',
        'user',
        'user'
      ])
      expect(body.messages[1]).toEqual({ role: 'assistant', content: 'generated reference' })
      expect(serialized.split(generatedImage.split(',')[1])).toHaveLength(2)
      expect(input).toEqual(before)
      expect(fetchImpl).toHaveBeenCalledOnce()
    }
  )
  it.each(['openai', 'claude'] as const)(
    '%s explicit latest-user-turn does not replay old user or assistant pictures',
    async (provider) => {
      const { client, fetchImpl } = setup(provider)
      await client.chat({ messages: messages(), imageHistoryPolicy: 'latest-user-turn' })
      const body = String(fetchImpl.mock.calls[0][1]?.body)
      expect(body).not.toContain(userImage.split(',')[1])
      expect(body).not.toContain(generatedImage.split(',')[1])
      expect(body).toContain('generated reference')
      expect(fetchImpl).toHaveBeenCalledOnce()
    }
  )
  it.each(['openai', 'claude'] as const)(
    '%s carries an image-only assistant reply without an empty assistant message',
    async (provider) => {
      const { client, fetchImpl } = setup(provider)
      await client.chat({
        messages: [
          { role: 'assistant', content: '', attachments: [{ type: 'image', url: generatedImage }] },
          { role: 'user', content: 'edit this generated image' }
        ],
        imageHistoryPolicy: 'all'
      })
      const body = JSON.parse(String(fetchImpl.mock.calls[0][1]?.body))
      expect(JSON.stringify(body.messages)).toContain(generatedImage.split(',')[1])
      expect(body.messages.every((m: { role: string }) => m.role === 'user')).toBe(true)
    }
  )
  it.each(['openai', 'claude'] as const)(
    '%s keeps the latest user image exactly once when old images are excluded',
    async (provider) => {
      const { client, fetchImpl } = setup(provider)
      const input = messages()
      input[2].attachments = [{ type: 'image', url: generatedImage }]
      await client.chat({ messages: input, imageHistoryPolicy: 'latest-user-turn' })
      const body = String(fetchImpl.mock.calls[0][1]?.body)
      expect(body).not.toContain(userImage.split(',')[1])
      expect(body.split(generatedImage.split(',')[1])).toHaveLength(2)
    }
  )
  it('Images edit includes the assistant-generated picture in multipart references', async () => {
    const fetchImpl = vi.fn<typeof fetch>().mockResolvedValue(
      new Response(JSON.stringify({ data: [{ b64_json: userImage.split(',')[1] }] }), {
        headers: { 'content-type': 'application/json' }
      })
    )
    const client = new OpenAIAPICli('owned', 'https://owned.test/v1', 'owned-image', {
      apiMode: 'images',
      modelUse: 'image',
      fetchImpl
    })
    const input = messages()
    const before = structuredClone(input)
    await client.chat({
      messages: input,
      imageGenerationOptions: { action: 'edit' },
      imageHistoryPolicy: 'all'
    })
    const body = fetchImpl.mock.calls[0][1]?.body
    expect(body).toBeInstanceOf(FormData)
    const files: Blob[] = []
    for (const value of (body as FormData).values()) if (value instanceof Blob) files.push(value)
    expect(files).toHaveLength(2)
    const contents = await Promise.all(
      files.map(async (file) => Buffer.from(await file.arrayBuffer()).toString('base64'))
    )
    expect(contents).toEqual([userImage.split(',')[1], generatedImage.split(',')[1]])
    expect(input).toEqual(before)
  })
})
