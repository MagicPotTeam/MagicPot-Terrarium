import React, { createRef } from 'react'
import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { beforeEach, afterEach, describe, expect, it, vi } from 'vitest'
import AgentThreadSkillsPanel from './AgentThreadSkillsPanel'
import type { AgentSkillCommandHandle } from '../agentSkillCommand'
const h = vi.hoisted(() => ({ show: vi.fn(), revision: vi.fn(), bind: vi.fn(), list: vi.fn(), change: vi.fn() }))
vi.mock('../../../utils/windowUtils', () => ({ api: () => ({ svcLLMProxy: { showAgentSessionSkill: h.show, agentSkillScopeRevision: h.revision, setAgentSkillScope: h.bind, listAgentSessionSkills: h.list, setAgentSkillPreference: h.change } }) }))
vi.mock('react-i18next', () => ({ useTranslation: () => ({ t: (key: string) => key }) }))
const route = { channel: 'canvas', scopeType: 'thread', scopeId: 'p', threadId: 't' } as const
const catalog = { revision: 1, skills: [{ id: 'one', name: 'Metadata skill', description: '<script>passive description</script>', paths: [], hidden: false, enabled: true }], truncated: false, staleDisabledIds: [], grantsPermission: false }
beforeEach(() => {
  vi.clearAllMocks(); h.show.mockReset().mockResolvedValue({ id: 'one', name: 'Metadata skill', instructions: '<script>USER_ONLY_BODY</script>', description: 'Metadata', paths: [], baseDirectory: 'D:/pack', enabled: false, revision: 1, untrustedData: true, grantsPermission: false, executed: false }); h.revision.mockResolvedValue({ revision: 200 }); h.bind.mockResolvedValue({ documentToken: 'fresh-token' }); h.list.mockResolvedValue(catalog); h.change.mockResolvedValue({ ...catalog, revision: 2, skills: [{ ...catalog.skills[0], enabled: false }] })
})
afterEach(() => { cleanup(); vi.restoreAllMocks() })
async function opened(conversationId: string) {
  const view = render(<AgentThreadSkillsPanel route={route} conversationId={conversationId} active />)
  await waitFor(() => expect(screen.getByRole('button', { name: 'chat.agent_skill_session.open' })).not.toBeDisabled())
  fireEvent.click(screen.getByRole('button', { name: 'chat.agent_skill_session.open' }))
  await screen.findByText('Metadata skill · chat.agent_skill_session.enabled')
  return view
}
describe('user-only conversation skill preferences panel', () => {
  it('binds lifecycle but loads no catalog automatically; explicit metadata view and CAS change are not model execution', async () => {
    const view = render(<AgentThreadSkillsPanel route={route} conversationId="normal" active />)
    await waitFor(() => expect(screen.getByRole('button', { name: 'chat.agent_skill_session.open' })).not.toBeDisabled())
    expect(h.list).not.toHaveBeenCalled(); expect(h.change).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole('button', { name: 'chat.agent_skill_session.open' }))
    expect(await screen.findByText('<script>passive description</script>')).toBeInTheDocument(); expect(document.querySelector('script')).toBeNull()
    expect(h.list).toHaveBeenCalledWith({ route, conversationId: 'normal', documentToken: 'fresh-token' })
    fireEvent.click(screen.getByRole('button', { name: 'chat.agent_skill_session.disable' }))
    await screen.findByText('Metadata skill · chat.agent_skill_session.disabled')
    expect(h.change).toHaveBeenCalledWith({ route, conversationId: 'normal', documentToken: 'fresh-token', id: 'one', enabled: false, expectedRevision: 1, operationId: expect.any(String) })
    view.unmount()
    expect(h.bind).toHaveBeenLastCalledWith({ route, conversationId: 'normal', active: false, lifecycleRevision: expect.any(Number) })
  })
  it('keeps an uncertain body-free operation identity across remount and does not create another edit', async () => {
    h.change.mockRejectedValueOnce(new Error('IPC uncertain'))
    const first = await opened('retry')
    fireEvent.click(screen.getByRole('button', { name: 'chat.agent_skill_session.disable' }))
    await screen.findByText('chat.agent_skill_session.failed')
    const original = h.change.mock.calls[0][0]
    expect(screen.getByRole('button', { name: 'chat.agent_skill_session.disable' })).toBeDisabled()
    first.unmount(); h.bind.mockResolvedValue({ documentToken: 'replacement-token' })
    const second = render(<AgentThreadSkillsPanel route={route} conversationId="retry" active />)
    await waitFor(() => expect(screen.getByRole('button', { name: 'chat.agent_skill_session.retry' })).not.toBeDisabled())
    fireEvent.click(screen.getByRole('button', { name: 'chat.agent_skill_session.retry' }))
    await screen.findByText('Metadata skill · chat.agent_skill_session.disabled')
    expect(h.change.mock.calls[1][0]).toEqual({ ...original, documentToken: 'replacement-token' })
    second.unmount()
  })
  it('never updates the new conversation after a delayed old preference save and retires its binding', async () => {
    let finish!: (result: unknown) => void
    h.change.mockImplementationOnce(() => new Promise(resolve => { finish = resolve }))
    const view = await opened('switch-a')
    fireEvent.click(screen.getByRole('button', { name: 'chat.agent_skill_session.disable' }))
    await waitFor(() => expect(h.change).toHaveBeenCalledOnce())
    view.rerender(<AgentThreadSkillsPanel route={route} conversationId="switch-b" active />)
    await act(async () => { finish({ ...catalog, skills: [{ ...catalog.skills[0], name: 'OLD_SCOPE_RESULT' }] }) })
    expect(screen.queryByText(/OLD_SCOPE_RESULT/)).not.toBeInTheDocument()
    expect(h.bind).toHaveBeenCalledWith({ route, conversationId: 'switch-a', active: false, lifecycleRevision: expect.any(Number) })
  })
  it('exposes explicit stale-denial cleanup without claiming global enable or loading bodies', async () => {
    h.list.mockResolvedValue({ ...catalog, skills: [], staleDisabledIds: ['stale-one'] }); h.change.mockResolvedValue({ ...catalog, revision: 2, skills: [] })
    render(<AgentThreadSkillsPanel route={route} conversationId="stale" active />)
    await waitFor(() => expect(screen.getByRole('button', { name: 'chat.agent_skill_session.open' })).not.toBeDisabled())
    fireEvent.click(screen.getByRole('button', { name: 'chat.agent_skill_session.open' }))
    await screen.findByText('stale-one')
    fireEvent.click(screen.getByRole('button', { name: 'chat.agent_skill_session.forget_stale' }))
    await waitFor(() => expect(h.change).toHaveBeenCalledWith(expect.objectContaining({ id: 'stale-one', enabled: true, expectedRevision: 1 })))
  })
  it('does not activate after a delayed high-water query belongs to an old scope, and StrictMode uses a fresh current binding', async () => {
    let finish!: (result: unknown) => void
    h.revision.mockImplementationOnce(() => new Promise(resolve => { finish = resolve }))
    const view = render(<AgentThreadSkillsPanel route={route} conversationId="highwater-old" active />)
    view.rerender(<AgentThreadSkillsPanel route={route} conversationId="highwater-new" active />)
    await waitFor(() => expect(h.bind).toHaveBeenCalledWith(expect.objectContaining({ conversationId: 'highwater-new', active: true })))
    await act(async () => { finish({ revision: 999 }) })
    expect(h.bind.mock.calls.some(([request]) => request.conversationId === 'highwater-old' && request.active)).toBe(false)
    view.unmount()
    h.revision.mockResolvedValue({ revision: 1000 })
    render(<React.StrictMode><AgentThreadSkillsPanel route={route} conversationId="strict" active /></React.StrictMode>)
    await waitFor(() => expect(screen.getByRole('button', { name: 'chat.agent_skill_session.open' })).not.toBeDisabled())
    expect(h.bind).toHaveBeenCalledWith(expect.objectContaining({ conversationId: 'strict', active: true, lifecycleRevision: expect.any(Number) }))
    const newest = h.bind.mock.calls.findLast(([request]) => request.conversationId === 'strict' && request.active)?.[0]
    expect(newest.lifecycleRevision).toBeGreaterThan(1000)
    expect(h.list).not.toHaveBeenCalled()
  })
  it.each(['query', 'activation'] as const)('allows explicit binding retry after a transient %s failure without loading a catalog or issuing a mutation', async failure => {
    if (failure === 'query') h.revision.mockRejectedValueOnce(new Error('query unavailable'))
    else h.bind.mockRejectedValueOnce(new Error('activation uncertain'))
    render(<AgentThreadSkillsPanel route={route} conversationId={`rebind-${failure}`} active />)
    await screen.findByText('chat.agent_skill_session.failed')
    expect(screen.getByRole('button', { name: 'chat.agent_skill_session.open' })).toBeDisabled()
    fireEvent.click(screen.getByRole('button', { name: 'chat.agent_skill_session.rebind' }))
    await waitFor(() => expect(screen.getByRole('button', { name: 'chat.agent_skill_session.open' })).not.toBeDisabled())
    expect(h.revision).toHaveBeenCalledTimes(2)
    expect(h.bind).toHaveBeenCalledWith(expect.objectContaining({ active: true, conversationId: `rebind-${failure}` }))
    expect(h.list).not.toHaveBeenCalled(); expect(h.change).not.toHaveBeenCalled()
  })
  it('unlocks only a matching structured pre-commit rejection, requiring refresh and a new explicit user choice', async () => {
    h.change.mockImplementationOnce(async request => ({ status: 'not-applied', operationId: request.operationId, reason: 'revision-conflict', currentRevision: 5 }))
    await opened('rejected')
    fireEvent.click(screen.getByRole('button', { name: 'chat.agent_skill_session.disable' }))
    await screen.findByText('chat.agent_skill_session.not_applied')
    expect(screen.queryByRole('button', { name: 'chat.agent_skill_session.retry' })).not.toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'chat.agent_skill_session.disable' })).not.toBeInTheDocument()
    expect(h.change).toHaveBeenCalledOnce()
    const original = h.change.mock.calls[0][0]
    h.list.mockResolvedValueOnce({ ...catalog, revision: 5 })
    fireEvent.click(screen.getByRole('button', { name: 'chat.agent_skill_session.open' }))
    await screen.findByText('Metadata skill · chat.agent_skill_session.enabled')
    expect(h.change).toHaveBeenCalledOnce()
    fireEvent.click(screen.getByRole('button', { name: 'chat.agent_skill_session.disable' }))
    await waitFor(() => expect(h.change).toHaveBeenCalledTimes(2))
    expect(h.change.mock.calls[1][0].expectedRevision).toBe(5)
    expect(h.change.mock.calls[1][0].operationId).not.toBe(original.operationId)
  })
  it('does not trust an error string or mismatched structured result as authority to discard an uncertain operation', async () => {
    h.change.mockRejectedValueOnce(new Error('Procedural skill preference revision conflict; refresh before changing.'))
    await opened('untrusted-rejection')
    fireEvent.click(screen.getByRole('button', { name: 'chat.agent_skill_session.disable' }))
    await screen.findByText('chat.agent_skill_session.failed')
    const original = h.change.mock.calls[0][0]
    h.change.mockResolvedValueOnce({ status: 'not-applied', operationId: 'foreign', reason: 'revision-conflict', currentRevision: 10 })
    fireEvent.click(screen.getByRole('button', { name: 'chat.agent_skill_session.retry' }))
    await waitFor(() => expect(h.change).toHaveBeenCalledTimes(2))
    expect(h.change.mock.calls[1][0]).toEqual(original)
    expect(screen.getByRole('button', { name: 'chat.agent_skill_session.disable' })).toBeDisabled()
    fireEvent.click(screen.getByRole('button', { name: 'chat.agent_skill_session.retry' }))
    await screen.findByText('Metadata skill · chat.agent_skill_session.disabled')
    expect(h.change.mock.calls[2][0]).toEqual(original)
  })
  it('does not release an unchanged revision from availability/capacity-shaped results; separate release requires two explicit steps and a refresh', async () => {
    h.change.mockResolvedValueOnce({ status: 'not-applied', operationId: 'unmatched', reason: 'capacity', currentRevision: 1 })
    await opened('separate')
    fireEvent.click(screen.getByRole('button', { name: 'chat.agent_skill_session.disable' }))
    await screen.findByText('chat.agent_skill_session.failed')
    expect(screen.getByRole('button', { name: 'chat.agent_skill_session.disable' })).toBeDisabled()
    fireEvent.click(screen.getByRole('button', { name: 'chat.agent_skill_session.separate' }))
    expect(screen.getByText('chat.agent_skill_session.separate_notice')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'chat.agent_skill_session.keep_pending' }))
    expect(screen.getByRole('button', { name: 'chat.agent_skill_session.disable' })).toBeDisabled()
    fireEvent.click(screen.getByRole('button', { name: 'chat.agent_skill_session.separate' }))
    fireEvent.click(screen.getByRole('button', { name: 'chat.agent_skill_session.confirm_separate' }))
    expect(h.change).toHaveBeenCalledOnce()
    expect(screen.queryByRole('button', { name: 'chat.agent_skill_session.disable' })).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'chat.agent_skill_session.open' }))
    await screen.findByText('Metadata skill · chat.agent_skill_session.enabled')
    expect(h.change).toHaveBeenCalledOnce()
  })
  it('runs user list/show/disable/enable/toggle commands without automatically viewing instruction bodies or widening scope', async () => {
    const ref = createRef<AgentSkillCommandHandle>(), scope = JSON.stringify({ route, conversationId: 'commands' })
    render(<AgentThreadSkillsPanel ref={ref} route={route} conversationId="commands" active />)
    await waitFor(() => expect(screen.getByRole('button', { name: 'chat.agent_skill_session.open' })).not.toBeDisabled())
    act(() => { expect(ref.current!.execute({ action: 'list' }, JSON.stringify({ route, conversationId: 'foreign' }))).toBe(false) })
    await act(async () => { expect(ref.current!.execute({ action: 'list' }, scope)).toBe(true) })
    expect(h.show).not.toHaveBeenCalled(); expect(h.change).not.toHaveBeenCalled()
    await act(async () => { expect(ref.current!.execute({ action: 'show', name: 'Metadata skill' }, scope)).toBe(true) })
    expect(h.show).toHaveBeenCalledWith({ route, conversationId: 'commands', documentToken: 'fresh-token', name: 'Metadata skill' })
    expect(screen.getByText('<script>USER_ONLY_BODY</script>')).toBeInTheDocument(); expect(document.querySelector('script')).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: 'chat.agent_skill_session.close_body' }))
    expect(screen.queryByText('<script>USER_ONLY_BODY</script>')).not.toBeInTheDocument()
    for (const action of ['disable', 'enable', 'toggle'] as const) {
      await act(async () => { expect(ref.current!.execute({ action, name: 'one' }, scope)).toBe(true) })
      expect(h.change).toHaveBeenLastCalledWith(expect.objectContaining({ id: 'one', enabled: action === 'enable', expectedRevision: 1 }))
    }
    expect(h.show).toHaveBeenCalledOnce()
  })
  it.each(['scope', 'eligibility'] as const)('does not dispatch a delayed toggle after %s revokes the command, or display a delayed body', async mode => {
    const ref = createRef<AgentSkillCommandHandle>(), scope = JSON.stringify({ route, conversationId: `delayed-${mode}` })
    const renderPanel = (enabled: boolean, id = `delayed-${mode}`) => <AgentThreadSkillsPanel ref={ref} route={route} conversationId={id} active commandEnabled={enabled} />
    const view = render(renderPanel(true)); await waitFor(() => expect(screen.getByRole('button', { name: 'chat.agent_skill_session.open' })).not.toBeDisabled())
    let finish!: (result: unknown) => void
    h.list.mockImplementationOnce(() => new Promise(resolve => { finish = resolve }))
    act(() => { expect(ref.current!.execute({ action: 'toggle', name: 'one' }, scope)).toBe(true); expect(ref.current!.execute({ action: 'show', name: 'one' }, scope)).toBe(false) })
    if (mode === 'scope') view.rerender(renderPanel(true, 'other-delayed'))
    else { view.rerender(renderPanel(false)); view.rerender(renderPanel(true)) }
    await act(async () => { finish(catalog) })
    expect(h.change).not.toHaveBeenCalled()
    await waitFor(() => expect(screen.getByRole('button', { name: 'chat.agent_skill_session.open' })).not.toBeDisabled())
    const currentScope = JSON.stringify({ route, conversationId: mode === 'scope' ? 'other-delayed' : `delayed-${mode}` })
    h.show.mockImplementationOnce(() => new Promise(resolve => { finish = resolve }))
    act(() => { expect(ref.current!.execute({ action: 'show', name: 'one' }, currentScope)).toBe(true) })
    view.unmount()
    await act(async () => { finish({ instructions: 'LATE_PRIVATE_BODY' }) })
    expect(screen.queryByText('LATE_PRIVATE_BODY')).not.toBeInTheDocument()
  })
  it('rejects ambiguous names without issuing a preference and preserves unknown toggle retries as a fixed action', async () => {
    const ref = createRef<AgentSkillCommandHandle>(), scope = JSON.stringify({ route, conversationId: 'ambiguous-toggle' })
    render(<AgentThreadSkillsPanel ref={ref} route={route} conversationId="ambiguous-toggle" active />)
    await waitFor(() => expect(screen.getByRole('button', { name: 'chat.agent_skill_session.open' })).not.toBeDisabled())
    h.list.mockResolvedValueOnce({ ...catalog, skills: [catalog.skills[0], { ...catalog.skills[0], id: 'two' }] })
    await act(async () => { ref.current!.execute({ action: 'toggle', name: 'Metadata skill' }, scope) })
    expect(h.change).not.toHaveBeenCalled()
    h.change.mockRejectedValueOnce(new Error('lost after toggle'))
    await act(async () => { ref.current!.execute({ action: 'toggle', name: 'one' }, scope) })
    const original = h.change.mock.calls[0][0]
    expect(original.enabled).toBe(false)
    act(() => { expect(ref.current!.execute({ action: 'toggle', name: 'one' }, scope)).toBe(false) })
    fireEvent.click(screen.getByRole('button', { name: 'chat.agent_skill_session.retry' }))
    await screen.findByText('Metadata skill · chat.agent_skill_session.disabled')
    expect(h.change.mock.calls[1][0]).toEqual(original)
  })
  it('does not bind inactive or ordinary chat surfaces', () => {
    const view = render(<AgentThreadSkillsPanel route={route} conversationId="inactive" active={false} />)
    view.rerender(<AgentThreadSkillsPanel conversationId="ordinary" active />)
    expect(h.bind).not.toHaveBeenCalled(); expect(h.list).not.toHaveBeenCalled()
  })
})
