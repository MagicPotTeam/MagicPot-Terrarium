import { lstat, mkdir, open, rename, rm } from 'node:fs/promises'
import path from 'node:path'
import { pathToFileURL } from 'node:url'

const KEY_ID = /^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$/
const BASE64_32 = /^(?:[A-Za-z0-9+/]{4}){10}[A-Za-z0-9+/]{3}=$/

function fail(message) { throw new Error(`bootstrap trust generation rejected: ${message}`) }

function parseArgs(argv) {
  const values = new Map()
  const allowed = new Set(['--output', '--descriptor-key-id', '--manifest-key-id', '--descriptor-public-key-base64', '--manifest-public-key-base64'])
  for (let index = 0; index < argv.length; index += 2) {
    const name = argv[index]
    const value = argv[index + 1]
    if (!allowed.has(name) || value === undefined || value.length === 0 || values.has(name)) fail('invalid command line')
    values.set(name, value)
  }
  for (const name of allowed) if (!values.has(name)) fail(`${name} is required`)
  return Object.fromEntries([...values].map(([name, value]) => [name.slice(2), value]))
}

function strictPublicKey(value, label) {
  if (!BASE64_32.test(value)) fail(`${label} must be canonical base64 for exactly 32 bytes`)
  const bytes = Buffer.from(value, 'base64')
  if (bytes.length !== 32 || bytes.toString('base64') !== value) fail(`${label} must be canonical base64 for exactly 32 bytes`)
  return bytes
}

function csString(value) {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`
}

export function generateBootstrapTrustSource(descriptorKeyId, descriptorPublicKeyBase64, manifestKeyId, manifestPublicKeyBase64) {
  if (!KEY_ID.test(descriptorKeyId) || descriptorKeyId.includes('..')) fail('--descriptor-key-id is invalid')
  if (!KEY_ID.test(manifestKeyId) || manifestKeyId.includes('..')) fail('--manifest-key-id is invalid')
  const descriptor = [...strictPublicKey(descriptorPublicKeyBase64, '--descriptor-public-key-base64')].join(', ')
  const manifest = [...strictPublicKey(manifestPublicKeyBase64, '--manifest-public-key-base64')].join(', ')
  return `// <auto-generated />\nusing System;\nusing System.Collections.Generic;\n\nnamespace MagicPot.Launcher;\n\ninternal static class CompiledBootstrapTrustConfiguration\n{\n    internal static BootstrapTrustConfiguration Create() => BootstrapTrustConfiguration.CreateCompiled(\n        true,\n        new Dictionary<string, byte[]>(StringComparer.Ordinal)\n        {\n            [${csString(descriptorKeyId)}] = new byte[] { ${descriptor} }\n        },\n        new Dictionary<string, byte[]>(StringComparer.Ordinal)\n        {\n            [${csString(manifestKeyId)}] = new byte[] { ${manifest} }\n        });\n}\n`
}

async function assertSafeOutput(output) {
  if (!path.isAbsolute(output)) fail('--output must be absolute')
  const resolved = path.resolve(output)
  if (path.extname(resolved).toLowerCase() !== '.cs' || path.basename(resolved) !== path.basename(output)) fail('--output must name a C# source file')
  await mkdir(path.dirname(resolved), { recursive: true })
  let current = path.parse(resolved).root
  for (const part of path.relative(current, path.dirname(resolved)).split(path.sep).filter(Boolean)) {
    current = path.join(current, part)
    const stat = await lstat(current)
    if (!stat.isDirectory() || stat.isSymbolicLink()) fail('--output parent path must contain only real directories')
  }
  try {
    const stat = await lstat(resolved)
    if (!stat.isFile() || stat.isSymbolicLink() || stat.nlink !== 1) fail('--output must be a single-link regular file when it exists')
  } catch (error) {
    if (error?.code !== 'ENOENT') throw error
  }
  return resolved
}

export async function main(argv = process.argv.slice(2)) {
  const args = parseArgs(argv)
  const output = await assertSafeOutput(args.output)
  const source = generateBootstrapTrustSource(args['descriptor-key-id'], args['descriptor-public-key-base64'], args['manifest-key-id'], args['manifest-public-key-base64'])
  const temporary = path.join(path.dirname(output), `.${path.basename(output)}.${process.pid}.${Date.now()}.tmp`)
  let handle
  try {
    handle = await open(temporary, 'wx', 0o600)
    await handle.writeFile(source, 'utf8')
    await handle.sync()
    await handle.close()
    handle = undefined
    await rename(temporary, output)
  } finally {
    await handle?.close().catch(() => {})
    await rm(temporary, { force: true }).catch(() => {})
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main().catch(error => { console.error(error.message); process.exitCode = 1 })
